#pragma once

#include <Arduino.h>

// Task — базовый класс для фоновой задачи.
//
// В отличие от App, задача не имеет своего GUI и не привязана к экрану:
// она просто существует и крутит Loop() каждый тик главного цикла,
// независимо от того, какое приложение сейчас открыто на экране.
//
// Типичный сценарий использования: "backend" (сама задача, например
// веб-сервер) + "frontend" (обычное App, которое эту задачу запускает,
// показывает её состояние на экране и даёт им управлять). Смотри
// apps/WebServer как пример такого разделения.
struct Task {
    virtual ~Task() {}

    virtual const char* GetName() const = 0;

    // Вызывается один раз при старте задачи (см. TaskManager::Start).
    virtual void Setup() {}

    // Вызывается каждый тик, пока задача жива.
    // Возвращает false, если задача сама решила завершиться
    // (после этого будет вызван Stop(), а объект уничтожен).
    virtual bool Loop() = 0;

    // Вызывается один раз при остановке задачи — как при попытке кем-то
    // явно её остановить (TaskManager::Stop), так и при завершении
    // задачи изнутри (Loop() вернул false).
    virtual void Stop() {}
};
