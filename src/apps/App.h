#pragma once

#include <Arduino.h>

// App — базовый класс приложения лаунчера (с GUI, живёт на экране).
//
// Лаунчер (main.cpp) создаёт НОВЫЙ экземпляр конкретного App-класса
// каждый раз при запуске приложения (нажатие BtnA на экране StartPrompt())
// и уничтожает его сразу после Exit(). Поэтому состояние приложения нужно
// хранить как обычные поля класса со значениями по умолчанию — сброс
// состояния в Setup() вручную, как правило, не требуется: свежий
// экземпляр и так "чистый". Setup() стоит использовать только для
// действий, которые действительно должны происходить один раз при
// старте (открыть файл/сокет, выделить буфер и т.п.), а не для
// обнуления переменных.
//
// Два разных вида методов — и это специально:
//
//   Setup() / Loop() / Exit()  — обычные виртуальные методы. У каждого
//   запущенного приложения свой экземпляр, поэтому они вызываются
//   ЧЕРЕЗ ЭКЗЕМПЛЯР: instance->Setup(), instance->Loop().
//
//   GetName() / StartPrompt() / AutoStart() — наоборот, static. Это
//   просто "паспортные данные" приложения: имя, текст на кнопке
//   запуска, нужно ли запускать его сразу при старте прошивки. Они не
//   зависят от того, запущено ли приложение и что у него сейчас в
//   полях — а нужны как раз ДО запуска (нарисовать имя в доке, текст
//   приглашения), поэтому лаунчеру больше не нужно держать отдельный
//   "пустой" экземпляр-прототип, только чтобы было у кого их спросить.
//   Вызываются они через класс: HomeApp::GetName(), не instance->GetName().
//
// В C++ не бывает виртуальных статических методов, поэтому базовый
// класс не может ЗАСТАВИТЬ наследника переопределить static-метод —
// компилятор об этом не предупредит. Если конкретный App не объявил
// свою версию, будет молча использована версия по умолчанию отсюда.
// Мороки чуть больше при написании нового App, зато исчезает целый
// класс prototype/active из main.cpp — см. AppSlot там.
//
// Если приложению нужно работать в фоне (когда открыт экран другого
// приложения) — см. Task.h и TaskManager.h.
struct App{
    virtual ~App() {}

    virtual void Setup() {}
    virtual bool Loop() = 0;
    virtual void Exit() {}

    // Значения по умолчанию — переопределяются в конкретных App-классах
    // такими же static-методами с тем же именем (перекрытие имени, а не
    // виртуальный override).
    static const char* GetName() { return "App"; }
    static const char* StartPrompt() { return "< START >"; }
    static bool AutoStart() { return false; }
};
